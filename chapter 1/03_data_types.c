#include <stdio.h>
int main() {
    int a = 10;
    float b = 3.14;
    double d = 3.141592;
    char c = 'A';
    char str[] = "Hello";

    printf("int a = %d\n", a);
    printf("float b = %f\n", b);
    printf("double d = %lf\n", d);
    printf("char c = %c\n", c);
    printf("string str = %s\n", str);

    return 0;
}
